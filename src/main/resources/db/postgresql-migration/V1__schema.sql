-- PetCARE schema for PostgreSQL 16+.
-- IDs such as U-1001 and P-1042 remain application-assigned so QR and audit references are unchanged.

CREATE OR REPLACE FUNCTION petcare_set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TABLE id_sequence (
  kind VARCHAR(10) PRIMARY KEY,
  prefix VARCHAR(10) NOT NULL,
  next_value BIGINT NOT NULL
);

CREATE TABLE app_user (
  id VARCHAR(20) PRIMARY KEY,
  role VARCHAR(10) NOT NULL,
  first_name VARCHAR(80), middle_name VARCHAR(80), last_name VARCHAR(80),
  full_name VARCHAR(160) NOT NULL,
  email VARCHAR(190) NOT NULL,
  mobile VARCHAR(30), house_street VARCHAR(160), barangay VARCHAR(80), city VARCHAR(80), province VARCHAR(80),
  password_hash VARCHAR(100) NOT NULL,
  status VARCHAR(30) NOT NULL,
  initials VARCHAR(4), job_title VARCHAR(80),
  must_change_password BOOLEAN NOT NULL DEFAULT FALSE,
  verification_code VARCHAR(10),
  created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_app_user_email UNIQUE (email),
  CONSTRAINT chk_app_user_role CHECK (role IN ('owner','staff','admin')),
  CONSTRAINT chk_app_user_status CHECK (status IN ('Active','Inactive','Pending Verification'))
);
CREATE INDEX ix_app_user_role ON app_user(role);
CREATE TRIGGER trg_app_user_updated_at BEFORE UPDATE ON app_user
  FOR EACH ROW EXECUTE FUNCTION petcare_set_updated_at();

CREATE TABLE veterinary_service (
  name VARCHAR(40) PRIMARY KEY,
  sort_order INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE eligibility_criterion (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  service_name VARCHAR(40) NOT NULL,
  criterion_key VARCHAR(30) NOT NULL,
  label VARCHAR(120) NOT NULL,
  description VARCHAR(600) NOT NULL,
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  sort_order INTEGER NOT NULL,
  CONSTRAINT uq_criterion UNIQUE (service_name, criterion_key),
  CONSTRAINT fk_criterion_service FOREIGN KEY (service_name) REFERENCES veterinary_service(name)
);

CREATE TABLE pet (
  id VARCHAR(20) PRIMARY KEY,
  owner_id VARCHAR(20) NOT NULL,
  name VARCHAR(80) NOT NULL,
  species VARCHAR(20) NOT NULL DEFAULT 'Dog',
  breed VARCHAR(80), sex VARCHAR(10) NOT NULL, dob DATE NOT NULL,
  color VARCHAR(120), barangay VARCHAR(80),
  registration_status VARCHAR(20) NOT NULL DEFAULT 'Pending',
  registered_date DATE,
  registration_source VARCHAR(10) NOT NULL DEFAULT 'Owner',
  weight_kg DECIMAL(5,2), health_status VARCHAR(30), health_notes VARCHAR(1000),
  rabies_status VARCHAR(20), last_rabies DATE,
  deworming_status VARCHAR(20), last_deworming DATE,
  proof_of_residency VARCHAR(40), microchip VARCHAR(40),
  microchip_status VARCHAR(20) NOT NULL DEFAULT 'Not Microchipped',
  kapon_status VARCHAR(20), kapon_date DATE, photo_url VARCHAR(500),
  created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_pet_microchip UNIQUE (microchip),
  CONSTRAINT fk_pet_owner FOREIGN KEY (owner_id) REFERENCES app_user(id),
  CONSTRAINT chk_pet_sex CHECK (sex IN ('Male','Female')),
  CONSTRAINT chk_pet_reg_status CHECK (registration_status IN ('Pending','Verified','Rejected')),
  CONSTRAINT chk_pet_reg_source CHECK (registration_source IN ('Owner','Walk-in')),
  CONSTRAINT chk_pet_weight CHECK (weight_kg IS NULL OR weight_kg > 0)
);
CREATE INDEX ix_pet_owner ON pet(owner_id);
CREATE INDEX ix_pet_reg_status ON pet(registration_status);
CREATE TRIGGER trg_pet_updated_at BEFORE UPDATE ON pet
  FOR EACH ROW EXECUTE FUNCTION petcare_set_updated_at();

CREATE TABLE pet_registration (
  id VARCHAR(20) PRIMARY KEY,
  pet_id VARCHAR(20) NOT NULL, owner_id VARCHAR(20) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'Pending', submitted_date DATE NOT NULL,
  source VARCHAR(10) NOT NULL DEFAULT 'Owner', rejection_reason VARCHAR(1000),
  reviewed_by VARCHAR(20), reviewed_at TIMESTAMP(6),
  CONSTRAINT fk_registration_pet FOREIGN KEY (pet_id) REFERENCES pet(id),
  CONSTRAINT fk_registration_owner FOREIGN KEY (owner_id) REFERENCES app_user(id),
  CONSTRAINT fk_registration_staff FOREIGN KEY (reviewed_by) REFERENCES app_user(id),
  CONSTRAINT chk_registration_status CHECK (status IN ('Pending','Verified','Rejected')),
  CONSTRAINT chk_registration_source CHECK (source IN ('Owner','Walk-in'))
);
CREATE INDEX ix_registration_pet ON pet_registration(pet_id);
CREATE INDEX ix_registration_status ON pet_registration(status);

CREATE TABLE service_request (
  id VARCHAR(20) PRIMARY KEY,
  pet_id VARCHAR(20) NOT NULL, owner_id VARCHAR(20) NOT NULL, service_name VARCHAR(40) NOT NULL,
  remarks VARCHAR(1000), submitted_date DATE NOT NULL,
  source VARCHAR(10) NOT NULL DEFAULT 'Owner',
  staff_decision VARCHAR(30) NOT NULL DEFAULT 'Pending',
  decision_date DATE, decided_by VARCHAR(20), rejection_reason VARCHAR(1000),
  status VARCHAR(20) NOT NULL DEFAULT 'Submitted',
  created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_request_pet FOREIGN KEY (pet_id) REFERENCES pet(id),
  CONSTRAINT fk_request_owner FOREIGN KEY (owner_id) REFERENCES app_user(id),
  CONSTRAINT fk_request_service FOREIGN KEY (service_name) REFERENCES veterinary_service(name),
  CONSTRAINT fk_request_staff FOREIGN KEY (decided_by) REFERENCES app_user(id),
  CONSTRAINT chk_request_source CHECK (source IN ('Owner','Walk-in','QR Scan')),
  CONSTRAINT chk_request_decision CHECK (staff_decision IN ('Pending','Approved','Rejected','Verification Requested')),
  CONSTRAINT chk_request_status CHECK (status IN ('Submitted','For Review','Approved','Rejected','Completed'))
);
CREATE INDEX ix_request_pet ON service_request(pet_id);
CREATE INDEX ix_request_owner ON service_request(owner_id);
CREATE INDEX ix_request_decision ON service_request(staff_decision,status);
CREATE TRIGGER trg_service_request_updated_at BEFORE UPDATE ON service_request
  FOR EACH ROW EXECUTE FUNCTION petcare_set_updated_at();

CREATE TABLE eligibility_assessment (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id VARCHAR(20) NOT NULL,
  classification VARCHAR(20) NOT NULL,
  assessed_date DATE NOT NULL, assessed_by VARCHAR(20),
  CONSTRAINT uq_assessment_request UNIQUE (request_id),
  CONSTRAINT fk_assessment_request FOREIGN KEY (request_id) REFERENCES service_request(id),
  CONSTRAINT fk_assessment_staff FOREIGN KEY (assessed_by) REFERENCES app_user(id),
  CONSTRAINT chk_assessment_class CHECK (classification IN ('ELIGIBLE','FOR REVIEW','NOT ELIGIBLE'))
);

CREATE TABLE eligibility_assessment_criterion (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assessment_id BIGINT NOT NULL, seq INTEGER NOT NULL,
  label VARCHAR(160) NOT NULL, actual_value VARCHAR(200), result VARCHAR(10) NOT NULL, basis VARCHAR(600),
  CONSTRAINT uq_assessment_seq UNIQUE (assessment_id,seq),
  CONSTRAINT fk_acrit_assessment FOREIGN KEY (assessment_id) REFERENCES eligibility_assessment(id) ON DELETE CASCADE,
  CONSTRAINT chk_acrit_result CHECK (result IN ('PASS','FAIL','REVIEW'))
);

CREATE TABLE service_record (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id VARCHAR(20) NOT NULL, record_date DATE NOT NULL, staff_name VARCHAR(120) NOT NULL,
  remarks VARCHAR(1000), vaccine_type VARCHAR(80), batch_number VARCHAR(60), next_due DATE,
  microchip_number VARCHAR(40), procedure_date DATE, post_remarks VARCHAR(1000),
  CONSTRAINT uq_record_request UNIQUE (request_id),
  CONSTRAINT fk_record_request FOREIGN KEY (request_id) REFERENCES service_request(id)
);

CREATE TABLE shelter_pet (
  id VARCHAR(20) PRIMARY KEY,
  name VARCHAR(80) NOT NULL, species VARCHAR(20) NOT NULL DEFAULT 'Dog', breed VARCHAR(80),
  sex VARCHAR(10) NOT NULL, age_text VARCHAR(40), description VARCHAR(1000), temperament VARCHAR(500),
  status VARCHAR(30) NOT NULL DEFAULT 'Available', intake_date DATE, photo_url VARCHAR(500),
  CONSTRAINT chk_shelter_sex CHECK (sex IN ('Male','Female')),
  CONSTRAINT chk_shelter_status CHECK (status IN ('Available','Application Pending','Adopted'))
);
CREATE INDEX ix_shelter_status ON shelter_pet(status);

CREATE TABLE adoption_application (
  id VARCHAR(20) PRIMARY KEY,
  shelter_pet_id VARCHAR(20) NOT NULL, applicant_owner_id VARCHAR(20) NOT NULL,
  applicant_name VARCHAR(160) NOT NULL, contact VARCHAR(40), email VARCHAR(190), address VARCHAR(255),
  barangay VARCHAR(80), reason VARCHAR(1000), experience VARCHAR(1000), housing VARCHAR(40),
  status VARCHAR(30) NOT NULL DEFAULT 'Interview Required', submitted_date DATE NOT NULL,
  rejection_reason VARCHAR(1000),
  CONSTRAINT fk_adoption_pet FOREIGN KEY (shelter_pet_id) REFERENCES shelter_pet(id),
  CONSTRAINT fk_adoption_applicant FOREIGN KEY (applicant_owner_id) REFERENCES app_user(id),
  CONSTRAINT chk_adoption_status CHECK (status IN ('Interview Required','Interview Completed','Approved','Rejected'))
);
CREATE INDEX ix_adoption_pet ON adoption_application(shelter_pet_id);
CREATE INDEX ix_adoption_applicant ON adoption_application(applicant_owner_id);

CREATE TABLE adoption_interview (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  adoption_id VARCHAR(20) NOT NULL, interview_date DATE NOT NULL, staff_name VARCHAR(120) NOT NULL,
  notes VARCHAR(2000), recommendation VARCHAR(40), checklist VARCHAR(1000),
  CONSTRAINT uq_interview_adoption UNIQUE (adoption_id),
  CONSTRAINT fk_interview_adoption FOREIGN KEY (adoption_id) REFERENCES adoption_application(id)
);

CREATE TABLE notification (
  id VARCHAR(20) PRIMARY KEY,
  user_id VARCHAR(20) NOT NULL, title VARCHAR(160) NOT NULL, body VARCHAR(1000) NOT NULL,
  created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  is_read BOOLEAN NOT NULL DEFAULT FALSE,
  CONSTRAINT fk_notification_user FOREIGN KEY (user_id) REFERENCES app_user(id)
);
CREATE INDEX ix_notification_user ON notification(user_id,is_read);

CREATE TABLE audit_log (
  id VARCHAR(20) PRIMARY KEY,
  occurred_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  user_id VARCHAR(20), user_name VARCHAR(160) NOT NULL, action VARCHAR(40) NOT NULL,
  module VARCHAR(60) NOT NULL, ref_id VARCHAR(40), description VARCHAR(1000),
  CONSTRAINT fk_audit_user FOREIGN KEY (user_id) REFERENCES app_user(id) ON DELETE SET NULL
);
CREATE INDEX ix_audit_time ON audit_log(occurred_at);
CREATE INDEX ix_audit_module_ref ON audit_log(module,ref_id);

